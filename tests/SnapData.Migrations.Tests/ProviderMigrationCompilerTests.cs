    private static MigrationPlan CreatePlan(string tableName, string referencedTable)
    {
        var plan = new MigrationPlan();
        using (var table = plan.CreateTable(tableName))
        {
            table.Identity();
            table.String("name", 120).Default("O'Brien");
            table.Boolean("active").Default(true);
            table.Guid("account_id");
            table.ForeignKey(
                "FK_users_accounts", ["account_id"], referencedTable, ["id"],
                onDelete: ReferentialAction.Cascade);
            table.Index("IX_users_name", "name");
        }
        return plan;
    }
