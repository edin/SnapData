        }
    }

    [Fact]
    public void Provider_specific_alter_syntax_is_preserved()
    {
        var plan = new MigrationPlan();
        plan.RenameColumn("app.users", "old_name", "new_name");
        plan.DropColumn("app.users", "obsolete");

        Assert.Equal(
            [
                "EXEC sp_rename N'[app].[users].[old_name]', N'new_name', N'COLUMN'",
                "ALTER TABLE [app].[users] DROP COLUMN [obsolete]"
            ],
            new SqlServerMigrationCompiler().Compile("001", MigrationDirection.Up, plan)
                .Statements.Select(statement => statement.Sql));
        var firebirdPlan = new MigrationPlan();
        firebirdPlan.RenameColumn("users", "old_name", "new_name");
        firebirdPlan.DropColumn("users", "obsolete");
        Assert.Equal(
            [
                "ALTER TABLE \"users\" ALTER COLUMN \"old_name\" TO \"new_name\"",
                "ALTER TABLE \"users\" DROP \"obsolete\""
            ],
            new FirebirdMigrationCompiler().Compile("001", MigrationDirection.Up, firebirdPlan)
                .Statements.Select(statement => statement.Sql));
    }

