using System.Text;
using SnapData.Migrations;

namespace SnapData.Migrations.Cli.Runtime;

internal sealed class MigrationScriptFileWriter
{
    private static readonly UTF8Encoding Utf8WithoutBom = new(false);

    public void Write(
        string outputFile,
        IReadOnlyList<MigrationScript> scripts,
        bool overwrite)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(outputFile);
        ArgumentNullException.ThrowIfNull(scripts);

        var fullPath = Path.GetFullPath(outputFile);
        var directory = Path.GetDirectoryName(fullPath)!;
        if (!Directory.Exists(directory))
        {
            throw new DirectoryNotFoundException(
                $"Output directory does not exist: {directory}");
        }
        if (!overwrite && File.Exists(fullPath))
        {
            throw new IOException(
                $"Output file already exists: {fullPath}. Use --force to replace it.");
        }

        var temporaryFile = Path.Combine(
            directory,
            $".{Path.GetFileName(fullPath)}.{Guid.NewGuid():N}.tmp");
        try
        {
            using (var stream = new FileStream(
                       temporaryFile,
                       FileMode.CreateNew,
                       FileAccess.Write,
                       FileShare.None))
            using (var writer = new StreamWriter(stream, Utf8WithoutBom))
            {
                WriteContent(writer, scripts);
                writer.Flush();
                stream.Flush(flushToDisk: true);
            }

            File.Move(temporaryFile, fullPath, overwrite);
        }
        finally
        {
            File.Delete(temporaryFile);
        }
    }

    private static void WriteContent(
        TextWriter writer,
        IReadOnlyList<MigrationScript> scripts)
    {
        writer.WriteLine("-- Generated by SnapData. Review before execution.");
        writer.WriteLine();
        foreach (var script in scripts)
        {
            writer.WriteLine($"-- Migration: {script.MigrationId}");
            for (var index = 0; index < script.Statements.Count; index++)
            {
                if (script.Statements.Count > 1)
                {
                    writer.WriteLine(
                        $"-- Statement: {index + 1}/{script.Statements.Count}");
                }

                var sql = script.Statements[index].Sql.Trim();
                writer.Write(sql);
                if (!sql.EndsWith(';'))
                {
                    writer.Write(';');
                }
                writer.WriteLine();
                writer.WriteLine();
            }
        }
    }
}
